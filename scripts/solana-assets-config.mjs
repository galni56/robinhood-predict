#!/usr/bin/env node
// Builds config/solana-assets.json — the single asset registry shared by the
// frontend, the admin scripts and the price collector — from the reviewed
// proposal in docs/solana-catalog/proposed.json.
//
// `approved` comes only from config/solana-catalog-approved.json, the owner's
// recorded decision; mainnet builds show approved assets only. Icons come from
// Jupiter's token API by mint.
//
// Usage: node scripts/solana-assets-config.mjs

import { readFileSync, writeFileSync } from 'node:fs'

const OUT = 'config/solana-assets.json'
const CATEGORY = { crypto: 'CRYPTO', meme: 'MEME', stock: 'STOCK' }
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

const proposal = JSON.parse(readFileSync('docs/solana-catalog/proposed.json', 'utf8'))
const approval = JSON.parse(readFileSync('config/solana-catalog-approved.json', 'utf8'))
const approvedSymbols = new Set(Object.values(approval.symbols).flat())
// Display/on-chain symbol where it differs from the Jupiter symbol.
const SYMBOL_OVERRIDES = { cbBTC: 'BTC', wXRP: 'XRP', wNEAR: 'NEAR' }
const NAME_OVERRIDES = { SOL: 'Solana', BTC: 'Bitcoin (cbBTC)', NEAR: 'NEAR (wrapped)', HYPE: 'Hyperliquid', ZEC: 'Zcash', PUMP: 'Pump.fun' }
// Scan pool kind -> price collector kind (scripts/solana/price-service/pools.mjs).
const POOL_KINDS = { 'pumpswap standard': 'pumpswap' }

async function tokenMeta(mint) {
  const res = await fetch(`https://lite-api.jup.ag/tokens/v2/search?query=${mint}`)
  if (!res.ok) return {}
  const [token] = (await res.json()).filter((t) => t.id === mint)
  return token ? { name: token.name, icon: token.icon } : {}
}

const assets = []
for (const p of proposal.proposed) {
  // On-chain asset ids are the symbol bytes; drop decoration such as "$WIF".
  const jupiterSymbol = p.symbol.replace(/^\$/, '')
  const symbol = SYMBOL_OVERRIDES[jupiterSymbol] ?? jupiterSymbol
  const meta = await tokenMeta(p.mint)
  await sleep(1100)
  assets.push({
    symbol,
    name: NAME_OVERRIDES[symbol] ?? meta.name ?? symbol,
    category: CATEGORY[p.category],
    mint: p.mint,
    tokenDecimals: p.decimals,
    // USD price precision signed by the collector. Sub-cent assets need more
    // digits so a percentage move stays measurable.
    priceDecimals: (p.priceUsdAtScan ?? 1) < 0.01 ? 12 : 8,
    pool: p.pool,
    poolKind: POOL_KINDS[p.poolKind] ?? p.poolKind,
    quote: p.quote,
    liquidityUsdAtScan: p.liquidityUsd,
    icon: meta.icon ?? null,
    priceUrl: p.url,
    approved: approvedSymbols.has(symbol),
  })
  process.stderr.write(`${symbol} `)
}

const out = {
  $comment: 'Generated by scripts/solana-assets-config.mjs from docs/solana-catalog/proposed.json; approval from config/solana-catalog-approved.json.',
  approvedAt: approval.approvedAt,
  scannedAt: proposal.scannedAt,
  usdcMint: 'EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v',
  solUsdcPool: assets.find((a) => a.symbol === 'SOL')?.pool ?? null,
  assets,
}
writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n')
console.log(`\nwrote ${OUT}: ${assets.length} assets (${assets.filter((a) => a.approved).length} approved)`)
